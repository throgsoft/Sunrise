/** Common rule predicates are ANDed with this optional source disjunction.
 * A weapon branch requires weaponKill=true and its exact authored class. An explicitly empty
 * disjunction matches nothing. Alternatives never create additional contributions to a lane.
 */
struct SourceAlternatives final {
    std::array<std::uint32_t, 4> weaponClasses{};
    bool grenade{};
    bool super{};
    bool precision{};
    bool ability{};
    /** Alternative selected-source slot; requires attributable weapon evidence. */
    std::optional<gameplay::WeaponSlot> weaponSlot{};
};

/** Sunrise-authored predicate selections keyed by item identity and objective ordinal.
 * Item/objective indices, thresholds and display names are deliberately absent from seeds;
 * the runtime resolves them from installed package definitions before evaluating a rule.
 */
struct KillRuleDefinition final {
    std::uint16_t itemIndex;
    std::uint32_t itemHash;
    std::uint16_t objectiveIndex;
    std::uint32_t objectiveHash;
    /** Item tail lane: manifest objective ordinal + 1; lane 0 is expiration. */
    std::uint8_t lane;
    std::int32_t completion;
    /** Exact authoritative activity index, or 0xFFFF for no activity restriction. */
    std::uint16_t activityIndex;
    /** Normalized FNV-1 race name, or zero for no additional race restriction.
     * This is NOT the raw canonical victim+0C class hash or a manifest race enum.
     */
    std::uint32_t raceHash;
    const char* name;
    std::uint32_t weaponClass{};
    std::optional<gameplay::Damage> damage{};
    bool weaponOnly{};
    bool grenadeOnly{};
    bool superOnly{};
    bool precisionOnly{};
    std::int32_t contribution{1};
    /** Total contribution for a precision kill, not an amount added to contribution.
     * Populate only from a reviewed objective-specific weighting; absent means no bonus.
     */
    std::optional<std::int32_t> precisionContribution{};
    std::optional<SourceAlternatives> anySource{};
    bool meleeOnly{};
    /** OR of gameplay::kRank*; zero imposes no rank requirement. This field only filters. */
    std::uint8_t victimRanks{};
    bool abilityOnly{};
    /** Reviewed zero-lifetime quest only; mapping validator must confirm installed lifetime zero.
     */
    bool nonExpiringQuest{};
    std::optional<areas::Requirement> area{};
    /** Killing source's native equipment slot, independent of damage and weapon class. */
    std::optional<gameplay::WeaponSlot> weaponSlot{};
    /** Exact installed actor-profile class; zero imposes no subtype restriction. */
    std::uint32_t victimClassHash{};
    /** Explicit user-adopted rank-point policy; never inferred for ordinary count lanes. */
    bool provisionalRankPoints{};
    /** Subclass equipped at native kill observation, independent of the attack's element. */
    std::optional<gameplay::Damage> equippedSubclassAffinity{};
};

