/** Grant an item once within a command's corpus, irrespective of objective count. */
[[nodiscard]] constexpr bool first_kill_rule_for_item(std::size_t row,
                                                      std::size_t first = 0) noexcept {
    if (row >= kKillRules.size() || first > row) return false;
    for (auto prior = first; prior < row; ++prior)
        if (kKillRules[prior].itemIndex == kKillRules[row].itemIndex) return false;
    return true;
}

[[nodiscard]] constexpr std::size_t
kill_rule_item_count(std::size_t first = 0, std::size_t end = kKillRules.size()) noexcept {
    if (end > kKillRules.size()) return 0;
    std::size_t count = 0;
    for (auto row = first; row < end; ++row)
        if (first_kill_rule_for_item(row, first)) ++count;
    return count;
}

